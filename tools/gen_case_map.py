#!/usr/bin/env python3
"""Regenerate src/core/expr/case_map.zig from DuckDB's own upper() and lower().

DuckDB maps case one code point at a time (utf8proc's simple mapping), so zpq's upper() and lower() must apply the
same table to give the same text. Run with a DuckDB CLI of the version zpq is checked against:

    tools/gen_case_map.py ~/.cache/zpq-duckdb2/bin-2.0.1/duckdb > src/core/expr/case_map.zig
"""
import csv, subprocess, sys, tempfile, os

duckdb = sys.argv[1]
with tempfile.TemporaryDirectory() as d:
    out = os.path.join(d, "map.csv")
    sql = (
        "COPY (SELECT cp, unicode(upper(chr(cp::INTEGER))) AS up, unicode(lower(chr(cp::INTEGER))) AS lo, "
        "length(upper(chr(cp::INTEGER))) AS ul, length(lower(chr(cp::INTEGER))) AS ll "
        "FROM range(1, 1114112) t(cp) WHERE cp NOT BETWEEN 55296 AND 57343 AND "
        "(chr(cp::INTEGER) <> upper(chr(cp::INTEGER)) OR chr(cp::INTEGER) <> lower(chr(cp::INTEGER)))) "
        f"TO '{out}' (HEADER, DELIMITER ',')"
    )
    subprocess.run([duckdb, "-no-agent", "-init", "/dev/null", "-c", sql], check=True)
    rows = list(csv.DictReader(open(out)))
for r in rows:
    assert r["ul"] == "1" and r["ll"] == "1", f"a multi-character mapping at U+{int(r['cp']):04X}: the table is one code point to one"

def ranges(pairs):
    """Runs of code points `lo, lo + stride, ...` that all move by one delta."""
    pairs = sorted(pairs)
    have = dict(pairs)
    out = []
    i = 0
    while i < len(pairs):
        cp, to = pairs[i]
        delta = to - cp
        stride = 1
        if have.get(cp + 1) is None or have[cp + 1] - (cp + 1) != delta:
            stride = 2 if have.get(cp + 2) is not None and have[cp + 2] - (cp + 2) == delta else 1
        hi = cp
        while have.get(hi + stride) is not None and have[hi + stride] - (hi + stride) == delta:
            hi += stride
        out.append((cp, hi, stride, delta))
        i += 1
        while i < len(pairs) and pairs[i][0] <= hi:
            i += 1
    return out

def emit(name, pairs):
    rs = ranges(pairs)
    # every pair is covered exactly once (an in-between code point of a stride-2 run would be lost, and this fails)
    covered = {}
    for lo, hi, stride, delta in rs:
        for c in range(lo, hi + 1, stride):
            assert c not in covered
            covered[c] = c + delta
    assert covered == dict(pairs), name
    print(f"pub const {name} = [_]Range{{")
    for lo, hi, stride, delta in rs:
        print(f"    .{{ .lo = 0x{lo:X}, .hi = 0x{hi:X}, .stride = {stride}, .delta = {delta} }},")
    print("};\n")

upper = [(int(r["cp"]), int(r["up"])) for r in rows if r["up"] != r["cp"]]
lower = [(int(r["cp"]), int(r["lo"])) for r in rows if r["lo"] != r["cp"]]
print("//! DuckDB's upper() and lower(), one code point to one, as ranges. Generated by tools/gen_case_map.py; do not edit.")
print("const std = @import(\"std\");\n")
print("pub const Range = struct { lo: u32, hi: u32, stride: u8, delta: i32 };\n")
emit("upper_ranges", upper)
emit("lower_ranges", lower)
print('''fn lookup(ranges: []const Range, cp: u32) u32 {
    // The last range starting at or before `cp`.
    var lo: usize = 0;
    var hi: usize = ranges.len;
    while (lo < hi) {
        const mid = lo + (hi - lo) / 2;
        if (ranges[mid].lo <= cp) lo = mid + 1 else hi = mid;
    }
    if (lo == 0) return cp;
    const r = ranges[lo - 1];
    if (cp > r.hi or (cp - r.lo) % r.stride != 0) return cp;
    return @intCast(@as(i64, cp) + r.delta);
}

pub fn upper(cp: u32) u32 {
    return lookup(&upper_ranges, cp);
}

pub fn lower(cp: u32) u32 {
    return lookup(&lower_ranges, cp);
}
''')
