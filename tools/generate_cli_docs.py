#!/usr/bin/env python3
"""Generate shell completions and the manual from the CLI's embedded help source."""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def outputs():
    help_text = (ROOT / "src/cli/help.txt").read_text()
    assert all(len(line) <= 80 for line in help_text.splitlines()), "help exceeds 80 columns"
    commands = sorted(set(re.findall(r"^  zpq ([a-z]+)", help_text, re.M)) | {"help", "version"})
    options = sorted((set(re.findall(r"(?<![\w-])--[a-z][a-z-]+", help_text)) - {"--summary"}) | {"--summary=json"})
    aliases = sorted(set(re.findall(r"(?<![\w-])-[a-zA-Z](?![\w-])", help_text)))
    words = " ".join(commands + options + aliases)
    bash = f'''# Generated by tools/generate_cli_docs.py; edit src/cli/help.txt.
_zpq() {{
  local cur="${{COMP_WORDS[COMP_CWORD]}}" prev="${{COMP_WORDS[COMP_CWORD-1]}}"
  case "$prev" in
    --format) COMPREPLY=($(compgen -W 'ndjson json parquet' -- "$cur")); return ;;
    --codec) COMPREPLY=($(compgen -W 'snappy zstd gzip lz4 lz4_raw uncompressed' -- "$cur")); return ;;
  esac
  if [[ "$cur" == -* || $COMP_CWORD == 1 ]]; then
    COMPREPLY=($(compgen -W '{words}' -- "$cur"))
  else
    COMPREPLY=(); while IFS= read -r item; do COMPREPLY+=("$item"); done < <(compgen -f -- "$cur")
  fi
}}
complete -F _zpq zpq
'''
    zsh = "#compdef zpq\n# Generated; edit src/cli/help.txt.\n"
    zsh += "if (( CURRENT == 2 )); then _values command " + " ".join(commands) + "; return; fi\n"
    zsh += "_arguments '*:file:_files' \\\n"
    zsh += " \\\n".join("  " + repr(option + "[zpq option]") for option in options + aliases) + "\n"
    fish = "# Generated; edit src/cli/help.txt.\n"
    fish += "complete -c zpq -n '__fish_use_subcommand' -a '" + " ".join(commands) + "'\n"
    fish += "".join("complete -c zpq -l " + option[2:] + "\n" for option in options if "=" not in option)
    fish += "complete -c zpq -a '--summary=json'\n"
    fish += "".join("complete -c zpq -s " + option[1:] + "\n" for option in aliases)
    man = '.TH ZPQ 1 "" "ZPQ" "User Commands"\n.SH NAME\nzpq \\- inspect and query Parquet\n.SH USAGE\n.nf\n'
    man += help_text.replace("\\", "\\e").replace("-", "\\-") + ".fi\n"
    return {
        "packaging/completions/zpq.bash": bash,
        "packaging/completions/_zpq": zsh,
        "packaging/completions/zpq.fish": fish,
        "packaging/man/zpq.1": man,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, text in outputs().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f"stale {name}; run tools/generate_cli_docs.py")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    print("CLI help, completions and manual are in sync")


if __name__ == "__main__":
    main()
