#!/usr/bin/env python3
"""Stage a formula from verified release hashes, with an explicit private rehearsal URL override."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("manifest")
    p.add_argument("--base-url", help="immutable artifact URL prefix; defaults to the manifest version release")
    p.add_argument("--out", default="packaging/homebrew/zpq.rb")
    p.add_argument("--allow-missing", action="store_true", help="private rehearsal: disable unbuilt platforms")
    a = p.parse_args()
    m = json.loads(Path(a.manifest).read_text())
    base_url = a.base_url or f"https://github.com/chicagobuss/zpq/releases/download/v{m['version']}"

    def fields(target, indent):
        if target not in m["artifacts"]:
            if not a.allow_missing:
                raise SystemExit("missing verified artifact: " + target)
            return indent + 'disable! date: "1970-01-01", because: "a verified binary is unavailable"\n'
        artifact = m["artifacts"][target]
        return (f'{indent}url "{base_url.rstrip("/")}/{artifact["file"]}"\n'
                f'{indent}sha256 "{artifact["sha256"]}"\n')

    text = '''# Staged upstream tarballs, not Homebrew bottles. Generated by tools/homebrew_formula.py.
require "json"

class Zpq < Formula
  desc "Fast Unix-native Parquet inspection, filtering and projection"
  homepage "https://github.com/chicagobuss/zpq"
  version "0.5.0"
  license "MIT"

  on_macos do
    depends_on arch: :arm64
'''
    text += fields("aarch64-macos", "    ") + "  end\n\n  on_linux do\n    on_arm do\n"
    text += fields("aarch64-linux-musl", "      ") + "    end\n    on_intel do\n"
    text += fields("x86_64-linux-musl", "      ") + '''    end
  end

  def install
    bin.install "bin/zpq"
    bash_completion.install "share/bash-completion/completions/zpq"
    zsh_completion.install "share/zsh/site-functions/_zpq"
    fish_completion.install "share/fish/vendor_completions.d/zpq.fish"
    man1.install "share/man/man1/zpq.1"
    pkgshare.install "share/zpq/tiny.parquet"
    pkgshare.install "MANIFEST.json"
  end

  test do
    file = pkgshare/"tiny.parquet"
    filtered = JSON.parse(shell_output("#{bin}/zpq query #{file} --filter 'id = 2' --columns id,value"))
    assert_equal({"id" => 2, "value" => 20}, filtered)
    groups = shell_output("#{bin}/zpq query #{file} --group-by group --aggregate 'sum(value) AS total'")
    assert_equal [{"group" => "a", "total" => 30}, {"group" => "b", "total" => 30}],
                 groups.lines.map { |line| JSON.parse(line) }
  end
end
'''
    text = text.replace('version "0.5.0"', f'version "{m["version"]}"')
    path = Path(a.out)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


if __name__ == "__main__":
    main()
