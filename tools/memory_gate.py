#!/usr/bin/env python3
"""Memory gate: does a query's peak memory stay under --max-memory, and does the answer stay the same?

Runs a matrix of query shapes x budgets x -j, each in a cgroup scope of its own (systemd-run --user --scope) capped
well above the budget, so an overrun is measured rather than killing the host. Per run it records the scope's
`memory.peak` (anonymous memory plus any page cache the run itself faults in: inputs are read once before the matrix,
so their pages are charged elsewhere), the process's peak RSS (`VmHWM`, which counts the mapped input as well), the
exit status, the first error line, and a hash of stdout (of the rows, for a Parquet answer:
its bytes may follow the row-group boundaries budget and -j choose).

    memory_gate.py run --bin zig-out/bin/zpq --out base.jsonl [--cells REGEX] [--budgets 64M,256M] [--jobs 1,16]
    memory_gate.py report base.jsonl [tip.jsonl]          # per-cell table; with two files, before/after

The verdict per run: `ok` (answered, peak <= budget + slack), `over` (answered above it), `refused` (clean error),
`killed` (the scope cap or a signal), `diff` (answered, but stdout differs from the same shape's other answers).
Slack is fixed per run: `--slack` (default 48 MiB) plus 1 MiB per worker for thread stacks and per-thread arenas.

Datasets: the study set under ~/bench/zpq-general/data (override ZPQ_STUDY_DATA), ClickBench sub16 under
~/bench/zpq-fair/data/clickbench (ZPQ_CLICKBENCH_DATA), and the fixtures `--fixtures DIR` holds (dba_big, dba_rg16,
dict_heavy; generated by tools/memory_gate_fixtures.py).
"""
import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
import tempfile
import time

HOME = os.path.expanduser("~")
STUDY = os.environ.get("ZPQ_STUDY_DATA", f"{HOME}/bench/zpq-general/data")
CB = os.environ.get("ZPQ_CLICKBENCH_DATA", f"{HOME}/bench/zpq-fair/data/clickbench")
CB_SQL = os.environ.get("CLICKBENCH_SQL", f"{HOME}/bench/zpq-fair/repos/ClickBench/duckdb-parquet/queries.sql")
CPUS = os.environ.get("ZPQ_GATE_CPUS", "8-15,24-31")
MiB = 1 << 20

STUDY_SETS = ["carduniq", "heavy", "lstr1m", "sstr10m", "card10m", "card100k", "clustzipf", "nullszipf"]
CB_QUERIES = [4, 8, 13, 17, 33]


def study_queries(meta):
    K, k1 = meta["K"], meta["kcols"][0]
    return [
        ("q01", f"SELECT {K}, count(*) AS c FROM {{T}} GROUP BY {K} ORDER BY c DESC LIMIT 10"),
        ("q02", f"SELECT {K}, count(*) AS c FROM {{T}} WHERE f < 300 GROUP BY {K} ORDER BY c DESC LIMIT 10"),
        ("q03", f"SELECT {K}, count(*) AS c FROM {{T}} WHERE f < 10 GROUP BY {K} ORDER BY c DESC LIMIT 10"),
        ("q04", f"SELECT {K}, count(*) AS c, sum(v) AS s, avg(v) AS av, min(v) AS mn, max(v) AS mx FROM {{T}} "
                f"GROUP BY {K} ORDER BY c DESC LIMIT 10"),
        ("q05", f"SELECT {K}, count(*) AS c FROM {{T}} GROUP BY {K} LIMIT 10"),
        ("q06", f"SELECT {K}, count(*) AS c, sum(v) AS s FROM {{T}} GROUP BY {K}"),
        ("q07", "SELECT count(DISTINCT x) AS d FROM {T}"),
        ("q08", f"SELECT count(DISTINCT {k1}) AS d FROM {{T}}"),
        ("q09", f"SELECT {K}, count(DISTINCT x) AS d FROM {{T}} GROUP BY {K} ORDER BY d DESC LIMIT 10"),
        ("q10", "SELECT count(*) AS c, sum(v) AS s, min(v) AS mn, max(v) AS mx FROM {T} WHERE f < 10"),
        ("q11", "SELECT count(*) AS c, sum(v) AS s, min(v) AS mn, max(v) AS mx FROM {T} WHERE f < 300"),
        ("q12", "SELECT count(*) AS c, sum(v) AS s, min(v) AS mn, max(v) AS mx FROM {T} WHERE f < 900"),
        ("q13", f"SELECT count(*) AS c, sum(v) AS s FROM {{T}} WHERE {meta['point']}"),
        ("q14", f"SELECT {K}, sum(v) AS s FROM {{T}} GROUP BY {K} ORDER BY s DESC LIMIT 10"),
        ("q15", f"SELECT {K}, f, count(*) AS c FROM {{T}} GROUP BY {K}, f ORDER BY c DESC LIMIT 10"),
    ]


def cells(fixtures):
    """[(name, argv after `zpq query`, input paths)]"""
    out = []
    for ds in STUDY_SETS:
        meta = json.load(open(f"{STUDY}/meta/{ds}.json"))
        path = f"{STUDY}/{ds}.parquet"
        for qid, sql in study_queries(meta):
            out.append((f"{ds}/{qid}", ["--query", sql.replace("{T}", f"'{path}'")], [path]))
    if os.path.exists(CB_SQL):
        lines = [q.strip().rstrip(";") for q in open(CB_SQL) if q.strip()]
        glob = f"{CB}/sub16/*.parquet"
        files = sorted(os.path.join(f"{CB}/sub16", f) for f in os.listdir(f"{CB}/sub16")) if os.path.isdir(
            f"{CB}/sub16") else []
        for q in CB_QUERIES:
            out.append((f"cb16/Q{q}", ["--query", lines[q].replace("FROM hits", f"FROM '{glob}'")], files))
    # Writes: a GROUP BY answer, a filtered re-encode, a string re-encode, a plain copy.
    cu, c10, ls, hv = (f"{STUDY}/{d}.parquet" for d in ("carduniq", "card10m", "lstr1m", "heavy"))
    pq = ["-o", "-", "--format", "parquet"]
    out.append(("write/agg_carduniq", ["--query", f"SELECT k, count(*) AS c, sum(v) AS s FROM '{cu}' GROUP BY k"] + pq,
                [cu]))
    out.append(("write/filter_card10m", [c10, "--filter", "f < 300"] + pq, [c10]))
    out.append(("write/select_lstr1m", [ls, "--columns", "k,v", "--filter", "f < 900"] + pq, [ls]))
    out.append(("write/copy_heavy", [hv] + pq, [hv]))
    if fixtures:
        big, rg16, dh = (f"{fixtures}/{f}.parquet" for f in ("dba_big", "dba_rg16", "dict_heavy"))
        out.append(("dba/big_filter", ["--query", f"SELECT count(*) AS c FROM '{big}' WHERE s = 'x'"], [big]))
        out.append(("dba/big_group", ["--query", f"SELECT s, count(*) AS c FROM '{big}' GROUP BY s"], [big]))
        out.append(("dba/big_write", [big, "--filter", "n >= 0"] + pq, [big]))
        out.append(("dba/rg16_filter", ["--query", f"SELECT count(*) AS c, sum(n) AS t FROM '{rg16}' "
                                        f"WHERE s = 'x'"], [rg16]))
        out.append(("dba/rg16_write", [rg16, "--filter", "n >= 0"] + pq, [rg16]))
        out.append(("dict/top", ["--query", f"SELECT k, count(*) AS c FROM '{dh}' GROUP BY k ORDER BY c DESC LIMIT 10"],
                    [dh]))
        out.append(("dict/full", ["--query", f"SELECT k, sum(v) AS s FROM '{dh}' GROUP BY k"], [dh]))
        out.append(("dict/distinct", ["--query", f"SELECT count(DISTINCT k) AS d FROM '{dh}'"], [dh]))
    return out


def parse_size(s):
    m = re.fullmatch(r"(\d+)([KMG]?)B?", s.strip().upper())
    if not m:
        raise SystemExit(f"bad size {s}")
    return int(m.group(1)) << {"": 0, "K": 10, "M": 20, "G": 30}[m.group(2)]


def warm(paths, seen):
    for p in paths:
        if p in seen:
            continue
        seen.add(p)
        with open(p, "rb") as f:
            while f.read(16 << 20):
                pass


# Runs inside the scope: the command, then the scope's own memory.peak and the exit status, read from the cgroup the
# shell itself sits in (the scope systemd-run made). Stdout is a pipe to this process: a file written inside the scope
# would charge its page cache to the scope's peak.
WRAP = r'''
"$@" 2>"$ZG_STDERR"; rc=$?
cg=$(sed -n 's/^0:://p' /proc/self/cgroup)
printf '%s %s\n' "$rc" "$(cat /sys/fs/cgroup$cg/memory.peak 2>/dev/null || echo -1)" >"$ZG_META"
'''


def content_hash(reader, path):
    """A Parquet answer's rows, hashed: its bytes depend on row-group boundaries, which may follow budget and -j."""
    h = hashlib.sha256()
    p = subprocess.Popen(["systemd-run", "--user", "--scope", "--quiet", "--collect", "-pMemoryMax=8G", "--",
                          reader, "query", path], stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
    while chunk := p.stdout.read(1 << 20):
        h.update(chunk)
    return h.hexdigest()[:16] if p.wait() == 0 else "unreadable"


def run_one(binary, argv, budget, jobs, cap, timeout, reader):
    parquet = "parquet" in argv
    with tempfile.TemporaryDirectory(prefix="zpq-gate-", dir=os.environ.get("ZPQ_GATE_TMP")) as td:
        env = dict(os.environ, ZG_STDERR=f"{td}/err", ZG_META=f"{td}/meta")
        cmd = ["systemd-run", "--user", "--scope", "--quiet", "--collect", f"-pMemoryMax={cap}", "-pMemorySwapMax=0",
               "-pOOMPolicy=continue", "--", "taskset", "-c", CPUS, "sh", "-c", WRAP, "sh",
               "/usr/bin/time", "-f", "ZGTIME %e %M", "-o", f"{td}/time",
               binary, "query", *argv, "--max-memory", str(budget), "-j", str(jobs)]
        t0 = time.time()
        h = hashlib.sha256()
        p = subprocess.Popen(cmd, env=env, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE)
        sink = open(f"{td}/answer.parquet", "wb") if parquet else None
        timed_out = False
        while chunk := p.stdout.read(1 << 20):
            (sink.write if sink else h.update)(chunk)
            if time.time() - t0 > timeout:
                timed_out = True
                break
        if sink:
            sink.close()
        try:
            p.wait(timeout=max(1, timeout - (time.time() - t0)))
        except subprocess.TimeoutExpired:
            timed_out = True
            p.kill()
            p.wait()
        wall = time.time() - t0
        rc, peak = -1, -1
        if os.path.exists(f"{td}/meta"):
            parts = open(f"{td}/meta").read().split()
            rc, peak = int(parts[0]), int(parts[1])
        hwm, el = -1, wall
        if os.path.exists(f"{td}/time"):
            for line in open(f"{td}/time"):
                if line.startswith("ZGTIME"):
                    _, e, m = line.split()
                    el, hwm = float(e), int(m) * 1024
                elif "signal" in line and line.split()[-1].isdigit():
                    rc = 128 + int(line.split()[-1])
        digest = h.hexdigest()[:16]
        if parquet and rc == 0:
            digest = content_hash(reader, f"{td}/answer.parquet")
        err = ""
        if os.path.exists(f"{td}/err"):
            lines = [l for l in open(f"{td}/err", errors="replace").read().splitlines() if l.strip()]
            err = lines[-1][:240] if lines else ""
        return {"rc": rc, "peak": peak, "hwm": hwm, "secs": round(el, 3), "hash": digest, "err": err,
                "timed_out": timed_out}


def slack_for(jobs, base):
    return base + jobs * MiB


def verdict(r, slack_base):
    if r["timed_out"]:
        return "timeout"
    if r["rc"] in (137, 9) or r["rc"] > 128:
        return "killed"
    if r["rc"] != 0:
        return "refused"
    return "ok" if r["peak"] <= r["budget"] + slack_for(r["jobs"], slack_base) else "over"


def cmd_run(a):
    binary = os.path.abspath(a.bin)
    budgets = [parse_size(b) for b in a.budgets.split(",")]
    jobs = [int(j) for j in a.jobs.split(",")]
    rx = re.compile(a.cells) if a.cells else None
    todo = [c for c in cells(a.fixtures) if not rx or rx.search(c[0])]
    done = set()
    if a.resume and os.path.exists(a.out):
        for line in open(a.out):
            r = json.loads(line)
            done.add((r["cell"], r["budget"], r["jobs"]))
    seen = set()
    with open(a.out, "a") as out:
        for name, argv, paths in todo:
            warm(paths, seen)
            for budget in budgets:
                for j in jobs:
                    if (name, budget, j) in done:
                        continue
                    cap = min(parse_size(a.cap_max), max(parse_size(a.cap_min), 2 * budget + (2 << 30)))
                    r = run_one(binary, argv, budget, j, cap, a.timeout, os.path.abspath(a.reader or a.bin))
                    r.update(cell=name, budget=budget, jobs=j, cap=cap, tag=a.tag)
                    r["verdict"] = verdict(r, a.slack << 20)
                    out.write(json.dumps(r) + "\n")
                    out.flush()
                    print(f"{name:24s} {budget >> 20:6d}M -j{j:<2d} {r['verdict']:8s} peak {r['peak'] / MiB:8.1f} MiB "
                          f"x{r['peak'] / budget:5.2f} {r['secs']:7.2f}s {r['hash']} {r['err'][:70]}", flush=True)


def load(path):
    rows = {}
    for line in open(path):
        r = json.loads(line)
        rows[(r["cell"], r["budget"], r["jobs"])] = r
    return rows


def mark_diffs(rows, slack_base):
    """An answered run whose stdout differs from the shape's most common answered hash is `diff`."""
    by_cell = {}
    for r in rows.values():
        r["verdict"] = verdict(r, slack_base)
        if r["rc"] == 0:
            by_cell.setdefault(r["cell"], []).append(r["hash"])
    for r in rows.values():
        hs = by_cell.get(r["cell"], [])
        if r["rc"] == 0 and hs and r["hash"] != max(set(hs), key=hs.count):
            r["verdict"] = "diff"


def fmt(r):
    if r is None:
        return "-"
    v = r["verdict"]
    if v in ("ok", "over", "diff"):
        s = f"{r['peak'] / r['budget']:.2f}"
        return s + ("!" if v == "over" else "") + ("D" if v == "diff" else "")
    return {"refused": "R", "killed": "K", "timeout": "T"}[v]


def cmd_report(a):
    slack = a.slack << 20
    before = load(a.files[0])
    mark_diffs(before, slack)
    after = None
    if len(a.files) > 1:
        after = load(a.files[1])
        mark_diffs(after, slack)
    keys = sorted({(k[1], k[2]) for k in before} | ({(k[1], k[2]) for k in after} if after else set()))
    names = sorted({k[0] for k in before} | ({k[0] for k in after} if after else set()))
    hdr = [f"{b >> 20}M/j{j}" for b, j in keys]
    print("ratio = memory.peak / budget; ! = over budget + slack; R = refused; K = killed; D = answer differs")
    print(f"{'cell':24s} " + " ".join(f"{h:>13s}" for h in hdr))
    tallies = {}
    for n in names:
        cols = []
        for b, j in keys:
            x = before.get((n, b, j))
            if after is not None:
                y = after.get((n, b, j))
                cols.append(f"{fmt(x):>6s}>{fmt(y):<6s}")
                if x and y:
                    if x["rc"] == 0 and y["rc"] == 0 and x["hash"] != y["hash"]:
                        tallies.setdefault("answer changed", []).append(f"{n} {b >> 20}M j{j}")
                    if x["rc"] == 0 and y["rc"] != 0:
                        tallies.setdefault("answered before, not after", []).append(
                            f"{n} {b >> 20}M j{j}: {y['err'][:80]}")
            else:
                cols.append(f"{fmt(x):>13s}")
        print(f"{n:24s} " + " ".join(cols))
    for name, rows in ((("before", before),) + ((("after", after),) if after else ())):
        counts = {}
        worst = max((r for r in rows.values() if r["rc"] == 0), key=lambda r: r["peak"] / r["budget"], default=None)
        for r in rows.values():
            counts[r["verdict"]] = counts.get(r["verdict"], 0) + 1
        print(f"{name}: " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())) +
              (f"; worst answered {worst['cell']} {worst['budget'] >> 20}M j{worst['jobs']} "
               f"x{worst['peak'] / worst['budget']:.2f}" if worst else ""))
    for k, v in tallies.items():
        print(f"{k}: {len(v)}")
        for line in v:
            print(f"  {line}")


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("run")
    r.add_argument("--bin", required=True)
    r.add_argument("--out", required=True)
    r.add_argument("--tag", default="")
    r.add_argument("--cells", default="")
    r.add_argument("--budgets", default="64M,256M,1G,4G")
    r.add_argument("--jobs", default="1,16")
    r.add_argument("--fixtures", default="")
    r.add_argument("--reader", default="", help="zpq binary that reads Parquet answers back for their hash")
    r.add_argument("--slack", type=int, default=48, help="MiB")
    r.add_argument("--cap-min", default="4G")
    r.add_argument("--cap-max", default="12G")
    r.add_argument("--timeout", type=float, default=300)
    r.add_argument("--resume", action="store_true")
    q = sub.add_parser("report")
    q.add_argument("files", nargs="+")
    q.add_argument("--slack", type=int, default=48, help="MiB")
    a = p.parse_args()
    cmd_run(a) if a.cmd == "run" else cmd_report(a)


if __name__ == "__main__":
    main()
